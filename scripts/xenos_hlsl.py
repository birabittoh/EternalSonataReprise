PRELUDE_HEAD = """\
// Generated by scripts/xenos_hlsl.py -- do not edit.
// Source: %(source)s

cbuffer XeFloatConsts : register(b%(cb_float)d) { float4 c[256]; };
cbuffer XeBoolConsts  : register(b%(cb_bool)d) { uint4 xe_bools[2]; uint4 xe_loops[8]; };

bool xe_bool(uint index) {
    return (xe_bools[index >> 7u][(index >> 5u) & 3u] & (1u << (index & 31u))) != 0u;
}

// Loop constant: iteration count in bits 0..7, initial aL in 8..15, and the
// signed step added to aL each iteration in 16..23.
uint xe_loop(uint index) { return xe_loops[index >> 2u][index & 3u]; }
int xe_loop_count(uint v) { return int(v & 0xFFu); }
int xe_loop_start(uint v) { return int((v >> 8u) & 0xFFu); }
int xe_loop_step(uint v) { return int(v << 8u) >> 24; }
"""

# Alpha test, which is fixed function on the console and does not exist on any
# host this targets. RB_COLORCONTROL carries the compare function and
# RB_ALPHA_REF the reference value, and both are ordinary render state that the
# guest changes between draws, so baking them into the shader would mean a
# variant per (shader, function) pair. They arrive as constants instead and the
# branch is uniform, which costs nothing a real branch would not.
#
# The disabled case is spelled as ALWAYS by the runtime that fills this, so a
# shader with the alpha test off takes the same path with no discard.
PRELUDE_ALPHA_TEST = """\
cbuffer XeAlphaTest : register(b%(cb_alpha)d) {
    uint xe_alpha_func;  // xenos::CompareFunction
    float xe_alpha_ref;
    uint2 xe_alpha_pad;
};

void xe_alpha_test(float a) {
    bool pass;
    switch (xe_alpha_func) {
        case 0u:  pass = false;             break;  // never
        case 1u:  pass = a <  xe_alpha_ref; break;  // less
        case 2u:  pass = a == xe_alpha_ref; break;  // equal
        case 3u:  pass = a <= xe_alpha_ref; break;  // lessequal
        case 4u:  pass = a >  xe_alpha_ref; break;  // greater
        case 5u:  pass = a != xe_alpha_ref; break;  // notequal
        case 6u:  pass = a >= xe_alpha_ref; break;  // greaterequal
        default:  pass = true;              break;  // always
    }
    if (!pass) {
        discard;
    }
}
"""

PRELUDE_ALU = """\
// Xenos writes the scalar result of a dot product to every masked component.
float4 xe_dp4(float4 a, float4 b) { return dot(a, b).xxxx; }
float4 xe_dp3(float4 a, float4 b) { return dot(a.xyz, b.xyz).xxxx; }
float4 xe_dp2add(float4 a, float4 b, float4 c) {
    return (dot(a.xy, b.xy) + c.x).xxxx;
}
float4 xe_max4(float4 a) {
    return max(max(a.x, a.y), max(a.z, a.w)).xxxx;
}

// cnd* select per component against the first operand.
float4 xe_cndeq(float4 a, float4 b, float4 c) {
    return float4(a.x == 0.0f ? b.x : c.x, a.y == 0.0f ? b.y : c.y,
                  a.z == 0.0f ? b.z : c.z, a.w == 0.0f ? b.w : c.w);
}
float4 xe_cndge(float4 a, float4 b, float4 c) {
    return float4(a.x >= 0.0f ? b.x : c.x, a.y >= 0.0f ? b.y : c.y,
                  a.z >= 0.0f ? b.z : c.z, a.w >= 0.0f ? b.w : c.w);
}
float4 xe_cndgt(float4 a, float4 b, float4 c) {
    return float4(a.x > 0.0f ? b.x : c.x, a.y > 0.0f ? b.y : c.y,
                  a.z > 0.0f ? b.z : c.z, a.w > 0.0f ? b.w : c.w);
}

// D3D9 dst: { 1, a.y * b.y, a.z, b.w }.
float4 xe_dst(float4 a, float4 b) {
    return float4(1.0f, a.y * b.y, a.z, b.w);
}

// Relative constant reads are clamped into the bank rather than left out of
// bounds, which is undefined for a host constant buffer.
uint xe_ci(int index) { return (uint)clamp(index, 0, 255); }

// maxas writes the address register as floor(clamp(src, -256, 255) + 0.5).
int xe_maxas_addr(float v) { return int(floor(clamp(v, -256.0f, 255.0f) + 0.5f)); }
int xe_maxasf_addr(float v) { return int(floor(clamp(v, -256.0f, 255.0f))); }

// Clamped / flushed reciprocal variants, where the clamp is the opcode.
float xe_rcpc(float v) { return clamp(1.0f / v, -3.402823466e+38f, 3.402823466e+38f); }
float xe_rcpf(float v) { float r = 1.0f / v; return isinf(r) ? (r < 0.0f ? -0.0f : 0.0f) : r; }
float xe_rsqc(float v) { return clamp(rsqrt(v), -3.402823466e+38f, 3.402823466e+38f); }
float xe_rsqf(float v) { float r = rsqrt(v); return isinf(r) ? (r < 0.0f ? -0.0f : 0.0f) : r; }
float xe_logc(float v) { float r = log2(v); return isinf(r) && r < 0.0f ? -3.402823466e+38f : r; }
"""

# `cube` takes one operand already swizzled to .z_xy and returns the cube map
# coordinate as (T, S, 2 * major axis, face id). Transcribed from xenia's
# AluVectorOpcode::kCube lowering in dxbc_shader_translator_alu.cc.
PRELUDE_CUBE = """\
float4 xe_cube(float4 s) {
    float x = s.z, y = s.w, z = s.x;
    float tc, sc, ma, id;
    if (abs(z) >= abs(x) && abs(z) >= abs(y)) {
        bool n = z < 0.0f;
        tc = -y; sc = n ? -x : x; ma = 2.0f * z; id = n ? 5.0f : 4.0f;
    } else if (abs(y) >= abs(x)) {
        bool n = y < 0.0f;
        tc = n ? -z : z; sc = x; ma = 2.0f * y; id = n ? 3.0f : 2.0f;
    } else {
        bool n = x < 0.0f;
        tc = -y; sc = n ? z : -z; ma = 2.0f * x; id = n ? 1.0f : 0.0f;
    }
    return float4(tc, sc, ma, id);
}
"""


def _vector_emitters():
    def binary(op):
        return lambda s: "(%s %s %s)" % (s[0], op, s[1])

    def compare(op):
        return lambda s: "float4(%s %s %s)" % (s[0], op, s[1])

    def call(name, count):
        return lambda s: "%s(%s)" % (name, ", ".join(s[:count]))

    return {
        "add": binary("+"), "mul": binary("*"),
        "max": call("max", 2), "min": call("min", 2),
        "seq": compare("=="), "sgt": compare(">"),
        "sge": compare(">="), "sne": compare("!="),
        "frc": call("frac", 1), "trunc": call("trunc", 1),
        "floor": call("floor", 1),
        "mad": lambda s: "(%s * %s + %s)" % (s[0], s[1], s[2]),
        "cndeq": call("xe_cndeq", 3), "cndge": call("xe_cndge", 3),
        "cndgt": call("xe_cndgt", 3),
        "dp4": call("xe_dp4", 2), "dp3": call("xe_dp3", 2),
        "dp2add": call("xe_dp2add", 3), "max4": call("xe_max4", 1),
        "dst": call("xe_dst", 2), "cube": call("xe_cube", 1),
        "maxa": call("max", 2),  # address register write handled separately
    }


