#!/usr/bin/env python3
"""Offline Xenos shader -> HLSL emitter, for vertex and pixel shaders.

Reads the `.ucode` / `.header` pairs written by `extract_shaders.py`, decodes
them with `xenos_ucode.py`, and emits one HLSL source per shader. This is the
back end of the offline shader translation step: nothing here runs at game
time, and the output is meant to be compiled once by DXC/FXC into whatever the
backend consumes.

Two pieces of per-draw patching the guest's D3D does to the microcode are
replaced by host signature matching rather than reproduced:

* Vertex fetch is *lifted*. `vfetch` is not translated as an instruction; each
  shader's vertex input signature comes from the container's vertex fetch patch
  table (`xenos_ucode.vertex_fetch_table`), every entry becomes a `float4` input
  with the matching D3DDECLUSAGE semantic, and the fetch emits as a register
  move. The host input assembler does the format conversion that `sub_82267218`
  would otherwise have patched in, so the output is independent of the bound
  vertex declaration.
* Interpolators are named by *semantic key*, not by register. Both shader types
  carry an interpolator signature table (`xenos_ucode.interpolator_signature`)
  that `sub_822679A8` walks at draw time to renumber a pixel shader's input
  registers to match the bound vertex shader's. Emitting `TEXCOORD<key>` on both
  sides makes the host linker do that job instead.

Usage:
    python scripts/xenos_hlsl.py out/shaders/vs_020.ucode      # to stdout
    python scripts/xenos_hlsl.py out/shaders --all -o out/hlsl # every shader
    python scripts/xenos_hlsl.py out/shaders --all --check     # translate only

Deliberate divergences from the hardware, all of which matter only for values
a renderer should never depend on:

* `mul`/`muls` do not reproduce the Direct3D 9 "0 or denormal times anything is
  +0" rule; plain HLSL multiply is emitted.
* `rcp`, `rsq` and `log` are emitted as the plain HLSL intrinsic. The `*c`
  (clamped) and `*f` (flushed) variants of those opcodes do carry their
  infinity clamping, since there the clamp is the whole point of the opcode.
* Denormal flushing on operand read is not reproduced.
* `tfetch`'s per-instruction filter and aniso fields are ignored. Every texture
  fetch in this title sets them to "take it from the fetch constant", so all
  sampler state comes from the host sampler, which is where it belongs.
"""

