#!/usr/bin/env python3
"""Embeds the title's XLast rich-presence metadata into src/xlast.generated.h.

XGIUserSetContext publishes small (context, value) pairs and XAM turns them into
a localized presence string via the {cN} template in the title's XLast document.
The SDK resolves that from the XDBF resource the retail XEX carries under the
title ID, but this project's guest image is a stripped build that drops that
resource, so the SDK's own lookup finds nothing. Instead of re-adding the whole
blob to the guest image we hand the SDK the same XLast XML directly.

The XLast is emitted as a readable UTF-8 raw string literal (the SDK's XLast
parser scans the document as text, so the original UTF-16 encoding declaration
is irrelevant). Run automatically by CMake (see CMakeLists.txt) before
compiling. assets/default.xex is already a required codegen input, so no extra
asset needs to be checked in.
"""
import gzip
import importlib.util
import os
import struct
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
XEX_PATH = os.path.join(ROOT, "assets", "default.xex")
OUT_PATH = os.path.join(ROOT, "src", "xlast.generated.h")

XDBF_SECTION_METADATA = 0x0001
XDBF_ID_XLAST = 0x58535243  # 'XSRC'


def _load_gen_icon():
    """Reuse gen-icon.py's XEX/XDBF extraction (it already decrypts the title
    resource out of assets/default.xex) rather than duplicating it here."""
    path = os.path.join(ROOT, "scripts", "gen-icon.py")
    spec = importlib.util.spec_from_file_location("gen_icon", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def extract_xlast_xml(xex_path):
    gen_icon = _load_gen_icon()
    with open(xex_path, "rb") as f:
        data = f.read()
    if data[0:4] != b"XEX2":
        raise RuntimeError(f"{xex_path} is not an XEX2 file")

    header_size = struct.unpack_from(">I", data, 0x8)[0]
    security_offset = struct.unpack_from(">I", data, 0x10)[0]
    opt_headers = gen_icon._read_opt_headers(data)
    xdbf = gen_icon._find_title_resource(data, opt_headers, header_size, security_offset)

    _magic, _version, entry_count, entry_used, free_count, _free_used = struct.unpack_from(
        ">IIIIII", xdbf, 0
    )
    entries_off = 24
    entry_size = 18
    content_off = entries_off + entry_size * entry_count + 8 * free_count

    payload = None
    for i in range(entry_used):
        e_off = entries_off + i * entry_size
        section = struct.unpack_from(">H", xdbf, e_off)[0]
        entry_id = struct.unpack_from(">Q", xdbf, e_off + 2)[0]
        offset, size = struct.unpack_from(">II", xdbf, e_off + 10)
        if section == XDBF_SECTION_METADATA and entry_id == XDBF_ID_XLAST:
            payload = xdbf[content_off + offset : content_off + offset + size]
            break
    if payload is None:
        raise RuntimeError("no XSRC (XLast) entry in the title's XDBF resource")

    # XSRC layout: 12-byte section header, filename length + name, then the
    # decompressed/compressed sizes and a gzip stream of the XLast XML.
    fn_len = struct.unpack_from(">I", payload, 12)[0]
    p = 16 + fn_len
    _decompressed_size, compressed_size = struct.unpack_from(">II", payload, p)
    p += 8
    return gzip.decompress(payload[p : p + compressed_size])


def main():
    xml_bytes = extract_xlast_xml(XEX_PATH)
    text = xml_bytes.decode("utf-16-le")

    delimiter = "ES_XLAST"
    terminator = f"){delimiter}\""
    if terminator in text:
        raise RuntimeError(f"XLast text contains the raw-string terminator {terminator!r}")

    lines = [
        "#pragma once",
        "",
        "// Generated by scripts/gen-xlast.py from assets/default.xex. Do not edit by",
        "// hand or commit this file directly - it is rebuilt on every CMake configure.",
        "",
        "namespace eternalsonata {",
        "",
        "// The title's XLast rich-presence metadata, fed to",
        "// UserContextManager::SetXLastBytes at startup.",
        f'inline constexpr char kXLastXml[] = R"{delimiter}(',
    ]
    with open(OUT_PATH, "w", newline="\n", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")
        out.write(text)
        out.write(f"{terminator};\n\n")
        out.write("}  // namespace eternalsonata\n")

    print(f"+ wrote {OUT_PATH} ({len(text)} chars of XLast XML)")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # noqa: BLE001
        print(f"error: {exc}", file=sys.stderr)
        sys.exit(1)
