#!/usr/bin/env python3
"""Writes src/save_text.generated.h: the chapter names and save locations the
game's load menu shows, per language, for the start screen's Saves page.

They come from src/guest_data/text (the 360's tables) and, for the location
ids only the PS3 has, src/guest_data/ps3/text. The game's markup (`\\n`, `<dNN>`)
is flattened to one line.
"""

import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "src", "save_text.generated.h")

# Guest language blocks and the start screen's language codes.
LANGUAGES = [("JPN", "ja"), ("GBR", "en"), ("FRA", "fr"), ("ITA", "it"), ("DEU", "de"),
             ("ESP", "es")]


def read_blocks(path):
    blocks, current = {}, None
    with open(path, encoding="utf-8") as f:
        for line in f.read().splitlines()[1:]:
            m = re.fullmatch(r"\[(\w+)\]", line)
            if m:
                current = blocks.setdefault(m.group(1), {})
                continue
            if current is not None and "\t" in line:
                key, text = line.split("\t", 1)
                current[int(key)] = text
    return blocks


def flatten(text):
    text = text.replace("\\n", " ")
    text = re.sub(r"<[^>]*>", "", text)
    return re.sub(r"\s+", " ", text).strip()


def table(blocks, extra, lang):
    entries = dict(extra.get(lang, {}))
    entries.update(blocks.get(lang, {}))
    count = max(entries) + 1 if entries else 0
    return [flatten(entries.get(i, "")) for i in range(count)]


def c_string(text):
    out = '"'
    for b in text.encode("utf-8"):
        if b in (0x22, 0x5C):
            out += "\\" + chr(b)
        elif 0x20 <= b < 0x7F:
            out += chr(b)
        else:
            out += f"\\{b:03o}"
    return out + '"'


def emit(name, rows):
    lines = []
    for lang, values in rows:
        lines.append(f"inline constexpr const char* {name}{lang}[] = {{")
        lines += [f"    {c_string(v)}," for v in values]
        lines.append("};")
    lines.append(f"inline constexpr SaveTextTable {name}[] = {{")
    lines += [f"    {{{name}{lang}, {len(values)}}}," for lang, values in rows]
    lines.append("};")
    return lines


def main():
    text = os.path.join(ROOT, "src", "guest_data", "text")
    ps3 = os.path.join(ROOT, "src", "guest_data", "ps3", "text")
    chapters = read_blocks(os.path.join(text, "chapters.txt"))
    locations = read_blocks(os.path.join(text, "save_locations.txt"))
    ps3_locations = read_blocks(os.path.join(ps3, "save_locations.txt"))
    out = [
        "// Generated by scripts/gen-save-text.py from src/guest_data - DO NOT EDIT",
        "#pragma once",
        "",
        "namespace eternalsonata {",
        "",
        "struct SaveTextTable {",
        "  const char* const* text;",
        "  int count;",
        "};",
        "",
        "// The start screen's language codes, in the order of the tables below.",
        "inline constexpr const char* kSaveTextLanguages[] = {"
        + ", ".join(f'"{code}"' for _, code in LANGUAGES) + "};",
        "",
    ]
    out += emit("kSaveChapters", [(g, table(chapters, {}, g)) for g, _ in LANGUAGES])
    out.append("")
    out += emit("kSaveLocations", [(g, table(locations, ps3_locations, g)) for g, _ in LANGUAGES])
    out += ["", "}  // namespace eternalsonata", ""]
    data = "\n".join(out)
    if os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == data:
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
